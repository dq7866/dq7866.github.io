  var REV = {};
  Object.keys(DICT).forEach(function (k) { if (DICT[k] !== k && !REV[DICT[k]]) REV[DICT[k]] = k; });

  var SKIP_TAGS = { SCRIPT: 1, STYLE: 1, CODE: 1, PRE: 1, TEXTAREA: 1, INPUT: 1, SELECT: 1, OPTION: 1, CANVAS: 1 };

  function translate(root, map, originals, collect) {
    var walk = function (node) {
      for (var i = 0; i < node.childNodes.length; i++) {
        var c = node.childNodes[i];
        if (c.nodeType === 3) {
          var raw = c.nodeValue;
          var t = raw.trim();
          if (!t || !map[t]) continue;
          if (collect) originals.push({ node: c, text: raw });
          c.nodeValue = raw.replace(t, map[t]);
        } else if (c.nodeType === 1) {
          if (SKIP_TAGS[c.tagName]) continue;
          // 可翻译属性：placeholder / title / aria-label / alt / value
          var TBX_ATTRS = ["placeholder", "title", "aria-label", "alt"];
          for (var ai = 0; ai < TBX_ATTRS.length; ai++) {
            var aName = TBX_ATTRS[ai];
            if (c.hasAttribute(aName)) {
              var aVal = c.getAttribute(aName);
              var aTrim = aVal.trim();
              if (map[aTrim]) {
                if (collect) originals.push({ node: c, attr: aName, text: aVal });
                c.setAttribute(aName, aVal.replace(aTrim, map[aTrim]));
              }
            }
          }
          // value 属性：仅当当前值仍等于原始属性值（用户未修改）时才翻译
          if (c.tagName === "INPUT" && c.hasAttribute("value")) {
            var vOrig = c.getAttribute("value");
            var vTrim = vOrig.trim();
            if (map[vTrim] && c.value === vOrig) {
              if (collect) originals.push({ node: c, attr: "value", text: vOrig });
              c.setAttribute("value", vOrig.replace(vTrim, map[vTrim]));
              c.value = vOrig.replace(vTrim, map[vTrim]);
            }
          }
          if (c.hasAttribute && c.hasAttribute("data-no-i18n")) continue;
          if (c.classList && c.classList.contains("title")) {
            // 标题里含 <em>，整体替换
            var full = c.textContent.trim();
            if (map[full]) {
              if (collect) originals.push({ el: c, html: c.innerHTML });
              c.textContent = map[full];
              continue;
            }
          }
          walk(c);
        }
      }
    };
    walk(root || document.body);
  }

  var originals = null;

  function currentLang() {
    var l = document.documentElement.getAttribute("data-lang");
    if (l === "zh" || l === "en") return l;
    try { var s = localStorage.getItem("tbx-lang"); if (s === "zh" || s === "en") return s; } catch (e) {}
    return "zh";
  }

  function setLang(lang, persist) {
    var html = document.documentElement;
    if (lang === "en") {
      if (!originals) { originals = []; translate(document.body, DICT, originals, true); }
      html.setAttribute("data-lang", "en");
    } else {
      if (originals) {
        originals.forEach(function (o) {
          try { if (o.el) o.el.innerHTML = o.html; else if (o.attr) o.node.setAttribute(o.attr, o.text); else o.node.nodeValue = o.text; } catch (e) {}
        });
        originals = null;
      }
      html.setAttribute("data-lang", "zh");
    }
    if (persist) { try { localStorage.setItem("tbx-lang", lang); } catch (e) {} }
    document.querySelectorAll("[data-lang-toggle]").forEach(function (b) {
      b.textContent = lang === "en" ? "中" : "EN";
      b.setAttribute("aria-label", lang === "en" ? "切换到中文" : "Switch to English");
      b.setAttribute("title", lang === "en" ? "切换到中文" : "Switch to English（快捷键 L）");
    });
    try { window.dispatchEvent(new CustomEvent("tbx-lang-change", { detail: lang })); } catch (e) {}
  }

  function buildButton() {
    var inner = document.querySelector(".topbar-inner");
    if (!inner) return;
    var box = inner.querySelector(".tb-actions");
    if (!box) return;
    if (box.querySelector("[data-lang-toggle]")) return;
    var b = document.createElement("button");
    b.className = "tb-icon-btn";
    b.type = "button";
    b.setAttribute("data-lang-toggle", "1");
    b.style.fontSize = "12.5px";
    b.style.fontWeight = "700";
    b.textContent = "EN";
    b.addEventListener("click", function () { setLang(currentLang() === "en" ? "zh" : "en", true); });
    box.insertBefore(b, box.firstChild);
  }

  function init() {
    buildButton();
    setLang(currentLang(), false);
    document.addEventListener("keydown", function (e) {
      var tag = (e.target && e.target.tagName) || "";
      if (tag === "INPUT" || tag === "TEXTAREA" || tag === "SELECT" || (e.target && e.target.isContentEditable)) return;
      if (e.key === "l" || e.key === "L") { if (!e.ctrlKey && !e.metaKey && !e.altKey) setLang(currentLang() === "en" ? "zh" : "en", true); }
    });
  }

  /**
   * 翻译动态文本：根据当前语言返回对应字符串。
   * 中文模式原样返回；英文模式查词典，命中返回译文，未命中返回原文。
   * 支持模板：t("已复制 {n} 项", { n: 3 }) -> "Copied 3 items" / "已复制 3 项"
   */
  function t(zh, params) {
    if (typeof zh !== "string") return zh;
    var lang = currentLang();
    var out = zh;
    if (lang === "en" && Object.prototype.hasOwnProperty.call(DICT, zh)) out = DICT[zh];
    if (params && typeof params === "object") {
      Object.keys(params).forEach(function (k) {
        out = out.split("{" + k + "}").join(params[k]);
      });
    }
    return out;
  }

  window.TBX_i18n = { setLang: setLang, currentLang: currentLang, dict: DICT, t: t };
  window.t = t;

