export const ALL_PARTS = [...PARTS, ...DAILY_PARTS];
export const PART_BY_ID = Object.fromEntries(ALL_PARTS.map(p => [p.id, p]));

export const SYSTEM_BY_ID = Object.fromEntries(SYSTEMS.map(s => [s.id, s]));

export function partsOf(systemId) {
  if (systemId === 'body') return PARTS;
  if (systemId === 'daily') return DAILY_PARTS;
  return PARTS.filter(p => p.system === systemId);
}

// 内容自检：每个形状必须恰好 7 项功能、具备注意事项（构建时也会跑一遍）
export function validateData(log = false) {
  const bad = [];
  for (const p of ALL_PARTS) {
    if (!Array.isArray(p.funcs) || p.funcs.length !== 7) bad.push(`${p.id}: funcs=${p.funcs && p.funcs.length}`);
    if (!p.caution || p.caution.length < 12) bad.push(`${p.id}: caution 缺失`);
    if (!Array.isArray(p.pos) || p.pos.length !== 3) bad.push(`${p.id}: pos 非法`);
  }
  if (log && bad.length) console.warn('[人体形状数据] 校验未通过', bad);
  return bad;
}