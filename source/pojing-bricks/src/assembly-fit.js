// 为什么需要它：积木按整数占位格摆位，可真实机构的轴、轮毂、轴承座是严丝合缝的；
// 传动解算又容许「同轴但隔 2~3 格」的两件互相带动，中间那段在实体上就是空的。
// 于是图纸看起来像悬空件拼盘，离 SolidWorks 装配体差一截。
//
// 做法：给每件一个 ox/oy/oz（单位 = 格，可小数），只改「实体相对占位格的微位置」。
//   · 占位格 / 支撑 / 六邻贴合判定仍走整数坐标（validate、check-mech 结构层不受影响）
//   · world.applyXform 负责渲染，drive.mechPart 让旋转中心跟着一起挪（不会偏心）
//   · 存档与挑战模式用 {...d} 或 serialize，ox/oy/oz 都会原样保留
// 所有偏移都由求解器在满足「传动契约不变 + 8 相位零穿模」的前提下迭代求解。
//
// 表结构：{ 模型id: { off: { 零件索引: [ox, oy, oz] }, add: [追加的零件] } }

