/** 把补丁应用到图纸清单（原地改 list 引用，返回同一数组，保持 live binding） */
export function applyAssemblyFit(models) {
  for (const m of models) {
    const fit = ASSEMBLY_FIT[m.id];
    if (!fit) continue;
    if (fit.off) {
      m.list = m.list.map((d, i) => {
        const o = fit.off[i];
        return o ? { ...d, ox: o[0], oy: o[1], oz: o[2] } : d;
      });
    }
    // 追加件排在末尾，不改变已有零件的索引，off 表才不会错位
    if (fit.add && fit.add.length) m.list = m.list.concat(fit.add);
  }
  return models;
}
